// Windows: per-user scheduled tasks (D60), the equivalent of launchd's LaunchAgents and systemd's user units. Each job
// is two files in %LOCALAPPDATA%\hallway\tasks\ and one task:
//   <label>.json   the job (a ServiceSpec): what `hallway supervise` runs; the definition `hallway service` reads back
//   <label>.xml    the task, registered with `schtasks /Create /XML` as `\<label>`: at logon (RunAtLoad), as the user,
//                  only while they're logged on (no stored password, no administrator rights), no time limit, and
//                  its action is conhost --headless (no console window) running `node cli.js supervise <label>.json`
//   <label>.state.json  written by the supervisor: its PID, the job's, the last exit code
// The mapping: RunAtLoad → a LogonTrigger; KeepAlive → the supervisor restarting the job; stop → the supervisor's
// process tree killed (`taskkill /T`), the task ended and disabled, so the next logon doesn't start it either.
// Pure where it can be (the files are golden-tested); every command goes through a Runner, mocked in the tests.
import fs from 'node:fs';
import os from 'node:os';
// the OS's own paths for the files this reads and writes (they're real files, in tests too); the task's own paths
// are Windows ones, built with path.win32
import path from 'node:path';
import { ROOT } from '../config.js';
import { type Runner, type ServiceManager, ServiceManagerError, type ServiceSpec, type ServiceStatus, defaultRunner, removeFile, writeIfChanged } from './services.js';
import { readState, stateFileOf } from './supervise.js';

/** The job file: the spec as JSON, with a note for people. */
export function renderJob(spec: ServiceSpec): string {
  return `${JSON.stringify({ _: `Generated by Hallway (${spec.label}). Don't edit it: \`hallway service regenerate\` rewrites it.`, ...spec }, null, 2)}\n`;
}

/** The PATH a job file sets (for doctor), or null. */
export function jobPath(text: string): string | null {
  try {
    const env = (JSON.parse(text) as Partial<ServiceSpec>).env ?? {};
    const key = Object.keys(env).find((k) => k.toUpperCase() === 'PATH');
    return key ? env[key] : null;
  } catch {
    return null;
  }
}

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/** One argument on a Windows command line, quoted by the C runtime's rules (the inverse of splitCommandLine). */
export function quoteArg(a: string): string {
  if (a !== '' && !/[\s"]/.test(a)) return a;
  return `"${a.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\+)$/, '$1$1')}"`;
}

export interface TaskContext {
  /** `DOMAIN\user` (or `MACHINE\user`): whose logon starts it, and who it runs as. */
  user: string;
  /** The argv that supervises a job file: [node, cli.js, 'supervise']. */
  supervisor: string[];
  /** conhost.exe, which runs it with no console window (`--headless`). */
  conhost: string;
}

/** The task definition. Pure: test/fixtures/services/*.task.xml pin it. */
export function renderTask(spec: ServiceSpec, jobFile: string, ctx: TaskContext): string {
  const argv = [...ctx.supervisor, jobFile];
  const lines = [
    '<?xml version="1.0" encoding="UTF-16"?>',
    '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">',
    '  <RegistrationInfo>',
    `    <Description>${xml(`${spec.description}. Generated by Hallway: \`hallway service regenerate\` rewrites it.`)}</Description>`,
    `    <URI>\\${xml(spec.label)}</URI>`,
    '  </RegistrationInfo>',
    '  <Triggers>',
    ...(spec.runAtLoad ? ['    <LogonTrigger>', '      <Enabled>true</Enabled>', `      <UserId>${xml(ctx.user)}</UserId>`, '    </LogonTrigger>'] : []),
    '  </Triggers>',
    '  <Principals>',
    '    <Principal id="Author">',
    `      <UserId>${xml(ctx.user)}</UserId>`,
    '      <LogonType>InteractiveToken</LogonType>',
    '      <RunLevel>LeastPrivilege</RunLevel>',
    '    </Principal>',
    '  </Principals>',
    '  <Settings>',
    '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>',
    '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>',
    '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>',
    '    <AllowHardTerminate>true</AllowHardTerminate>',
    '    <StartWhenAvailable>false</StartWhenAvailable>',
    '    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>',
    '    <IdleSettings>',
    '      <StopOnIdleEnd>false</StopOnIdleEnd>',
    '      <RestartOnIdle>false</RestartOnIdle>',
    '    </IdleSettings>',
    '    <AllowStartOnDemand>true</AllowStartOnDemand>',
    '    <Enabled>true</Enabled>',
    '    <Hidden>false</Hidden>',
    '    <RunOnlyIfIdle>false</RunOnlyIfIdle>',
    '    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>',
    '    <Priority>7</Priority>',
    '  </Settings>',
    '  <Actions Context="Author">',
    '    <Exec>',
    `      <Command>${xml(ctx.conhost)}</Command>`,
    `      <Arguments>${xml(['--headless', ...argv].map(quoteArg).join(' '))}</Arguments>`,
    `      <WorkingDirectory>${xml(spec.cwd)}</WorkingDirectory>`,
    '    </Exec>',
    '  </Actions>',
    '</Task>',
    '',
  ];
  return lines.join('\r\n');
}

/** `schtasks /Query /XML`'s Settings → Enabled (absent means enabled). Null when it isn't a task definition. */
export function taskEnabled(text: string): boolean | null {
  const settings = /<Settings>([\s\S]*?)<\/Settings>/.exec(text);
  if (!settings) return null;
  // the Settings block's own <Enabled>, not one inside <IdleSettings> or a trigger
  const m = /^\s*<Enabled>(true|false)<\/Enabled>/m.exec(settings[1].replace(/<IdleSettings>[\s\S]*?<\/IdleSettings>/, ''));
  return m ? m[1] === 'true' : true;
}

export interface SchtasksOptions {
  /** %LOCALAPPDATA%\hallway\tasks. */
  dir: string;
  run?: Runner;
  ctx?: Partial<TaskContext>;
  /** Is this PID running? (Mocked in tests.) */
  isAlive?: (pid: number) => boolean;
}

const defaultIsAlive = (pid: number) => {
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return (e as NodeJS.ErrnoException).code === 'EPERM';
  }
};

export function defaultTaskContext(env: NodeJS.ProcessEnv = process.env): TaskContext {
  // the compiled CLI in this package (as Services' daemon job uses), in the OS's own form
  const cli = path.join(ROOT, 'dist', 'server', 'cli.js');
  let node = process.execPath;
  try {
    node = fs.realpathSync.native(process.execPath); // never a version manager's per-shell link (the PATH trap)
  } catch {
    /* keep it */
  }
  return {
    user: `${env.USERDOMAIN || os.hostname()}\\${env.USERNAME || os.userInfo().username}`,
    supervisor: [node, cli, 'supervise'],
    conhost: path.win32.join(env.SystemRoot || env.windir || 'C:\\Windows', 'System32', 'conhost.exe'),
  };
}

export function schtasksManager({ dir, run = defaultRunner, ctx: given = {}, isAlive = defaultIsAlive }: SchtasksOptions): ServiceManager {
  const ctx = (): TaskContext => ({ ...defaultTaskContext(), ...given });
  const file = (label: string) => path.join(dir, `${label}.json`);
  const xmlFile = (label: string) => path.join(dir, `${label}.xml`);
  const tn = (label: string) => `\\${label}`;

  const schtasks = async (args: string[], okCodes = [0]) => {
    const r = await run('schtasks', args);
    if (r.code === 127) throw new ServiceManagerError('schtasks is not available: Hallway manages services with Task Scheduler on Windows');
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`schtasks ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (label: string): Promise<ServiceStatus> => {
    const installed = fs.existsSync(file(label));
    const q = await run('schtasks', ['/Query', '/TN', tn(label), '/XML']);
    if (q.code === 127) throw new ServiceManagerError('schtasks is not available: Hallway manages services with Task Scheduler on Windows');
    const loaded = q.code === 0;
    const enabled = loaded ? taskEnabled(q.stdout) : null;
    const st = readState(stateFileOf(file(label)));
    const running = !!(st && st.pid && isAlive(st.pid) && isAlive(st.supervisor));
    return {
      label,
      installed,
      loaded,
      running,
      pid: running ? st!.pid : null,
      lastExitCode: st?.lastExitCode ?? null,
      state: !loaded ? null : running ? 'running' : enabled === false ? 'disabled' : 'stopped',
      enabled,
    };
  };

  /** End the supervisor and everything it started (taskkill /T), then the task itself. */
  const kill = async (label: string) => {
    const st = readState(stateFileOf(file(label)));
    if (st && isAlive(st.supervisor)) await run('taskkill', ['/PID', String(st.supervisor), '/T', '/F']);
    // exit 1 / "not running": fine
    await run('schtasks', ['/End', '/TN', tn(label)]);
  };

  return {
    kind: 'schtasks',
    noun: 'scheduled task',
    lifetime: 'It starts when you log on and is restarted if it exits. It stops when you log off (a task that runs without a logon would need your password stored, or administrator rights).',
    file,
    render: renderJob,
    readPath: jobPath,
    async write(spec) {
      const job = writeIfChanged(file(spec.label), renderJob(spec));
      const text = renderTask(spec, file(spec.label), ctx());
      // schtasks wants the XML as UTF-16 (with its byte order mark)
      let task = true;
      try {
        task = fs.readFileSync(xmlFile(spec.label), 'utf16le').replace(/^\uFEFF/, '') !== text;
      } catch {
        /* missing */
      }
      if (task) {
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(xmlFile(spec.label), `\uFEFF${text}`, 'utf16le');
      }
      const registered = (await run('schtasks', ['/Query', '/TN', tn(spec.label)])).code === 0;
      if (task || !registered) await schtasks(['/Create', '/TN', tn(spec.label), '/XML', xmlFile(spec.label), '/F']);
      return job || task;
    },
    async start(spec) {
      // a `stop` disabled it (so the next logon wouldn't start it): undo that, or /Run refuses
      await schtasks(['/Change', '/TN', tn(spec.label), '/ENABLE']);
      if ((await status(spec.label)).running) return;
      await schtasks(['/Run', '/TN', tn(spec.label)]);
    },
    async stop(label) {
      await kill(label);
      await schtasks(['/Change', '/TN', tn(label), '/DISABLE'], [0, 1]);
    },
    async restart(spec) {
      // the supervisor reads the job file at every start, so a changed one needs nothing more than this
      await kill(spec.label);
      await schtasks(['/Change', '/TN', tn(spec.label), '/ENABLE']);
      await schtasks(['/Run', '/TN', tn(spec.label)]);
    },
    status,
    async remove(label) {
      await kill(label);
      await schtasks(['/Delete', '/TN', tn(label), '/F'], [0, 1]);
      for (const f of [file(label), xmlFile(label), stateFileOf(file(label))]) removeFile(f);
    },
    list() {
      try {
        return fs
          .readdirSync(dir)
          .filter((f) => /^hallway\.[a-z0-9.-]+\.json$/.test(f) && !f.endsWith('.state.json'))
          .map((f) => f.slice(0, -'.json'.length))
          .sort();
      } catch {
        return [];
      }
    },
  };
}
