// macOS: launchd LaunchAgents in the gui/<uid> domain (docs/04-apps-health-services.md, "Generating launchd jobs").
// The plist follows the template in docs/04 exactly; the lifecycle uses the modern launchctl verbs (bootstrap,
// bootout, kickstart, print), plus enable/disable so that a stopped job stays stopped at the next login (D38).
// Behaviour checked only with the runner mocked is listed as "unverified on macOS" in docs/11-research-notes.md.
import fs from 'node:fs';
import path from 'node:path';
import { type Runner, type ServiceManager, ServiceManagerError, type ServiceSpec, type ServiceStatus, defaultRunner, removeFile, writeIfChanged } from './services.js';

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unxml = (s: string) => s.replace(/&quot;/g, '"').replace(/&gt;/g, '>').replace(/&lt;/g, '<').replace(/&amp;/g, '&');

/** The plist for a job. Pure: the golden files in test/fixtures/services/ pin it. */
export function renderPlist(spec: ServiceSpec): string {
  const key = (k: string) => `    <key>${k}</key>`;
  const str = (v: string) => `<string>${xml(v)}</string>`;
  const bool = (b: boolean) => (b ? '<true/>' : '<false/>');
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    `<!-- Generated by Hallway (${spec.label}). Don't edit it: \`hallway service regenerate\` rewrites it. -->`,
    ...(spec.node ? [`<!-- Node ${xml(spec.node.version)}: ${xml(spec.node.path).replace(/--/g, '- -')} -->`] : []),
    '<plist version="1.0">',
    '  <dict>',
    `${key('Label')}              ${str(spec.label)}`,
    key('ProgramArguments'),
    '    <array>',
    ...spec.program.map((a) => `      ${str(a)}`),
    '    </array>',
    `${key('RunAtLoad')}          ${bool(spec.runAtLoad)}`,
    `${key('KeepAlive')}          ${bool(spec.keepAlive)}`,
    `${key('ThrottleInterval')}   <integer>10</integer>`,
    `${key('WorkingDirectory')}   ${str(spec.cwd)}`,
    `${key('StandardOutPath')}    ${str(spec.stdout)}`,
    `${key('StandardErrorPath')}  ${str(spec.stderr)}`,
    key('EnvironmentVariables'),
    '    <dict>',
    ...Object.entries(spec.env).map(([k, v]) => `      <key>${xml(k)}</key>${' '.repeat(Math.max(1, 9 - k.length))}${str(v)}`),
    '    </dict>',
    '  </dict>',
    '</plist>',
    '',
  ];
  return lines.join('\n');
}

/** The PATH an existing plist sets (for doctor), or null. */
export function plistPath(text: string): string | null {
  const m = /<key>PATH<\/key>\s*<string>([^<]*)<\/string>/.exec(text);
  return m ? unxml(m[1]) : null;
}

/** `launchctl print gui/<uid>/<label>`: the job's top-level `state`, `pid` and `last exit code`. */
export function parseLaunchctlPrint(text: string): { state: string | null; pid: number | null; lastExitCode: number | null } {
  const top = (k: string) => new RegExp(`^\\t${k} = (.+)$`, 'm').exec(text)?.[1].trim() ?? null;
  const pid = top('pid');
  const exit = top('last exit code');
  return {
    state: top('state'),
    pid: pid && /^\d+$/.test(pid) ? Number(pid) : null,
    lastExitCode: exit && /^-?\d+$/.test(exit) ? Number(exit) : null,
  };
}

export interface LaunchdOptions {
  /** ~/Library/LaunchAgents. */
  dir: string;
  uid: number;
  run?: Runner;
  /** For the bootout → bootstrap retry. */
  sleep?: (ms: number) => Promise<void>;
}

export function launchdManager({ dir, uid, run = defaultRunner, sleep = (ms) => new Promise((r) => setTimeout(r, ms)) }: LaunchdOptions): ServiceManager {
  const domain = `gui/${uid}`;
  const target = (label: string) => `${domain}/${label}`;
  const file = (label: string) => path.join(dir, `${label}.plist`);

  const launchctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('launchctl', args);
    if (r.code === 127) throw new ServiceManagerError('launchctl is not available: Hallway manages services with launchd on macOS');
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`launchctl ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (label: string): Promise<ServiceStatus> => {
    const installed = fs.existsSync(file(label));
    const r = await run('launchctl', ['print', target(label)]);
    if (r.code === 127) throw new ServiceManagerError('launchctl is not available: Hallway manages services with launchd on macOS');
    if (r.code !== 0) return { label, installed, loaded: false, running: false, pid: null, lastExitCode: null, state: null, enabled: null };
    const p = parseLaunchctlPrint(r.stdout);
    return { label, installed, loaded: true, running: p.state === 'running' && p.pid !== null, pid: p.pid, lastExitCode: p.lastExitCode, state: p.state, enabled: null };
  };

  // Right after a bootout, the job may still be on its way out, and bootstrap fails with "5: Input/output error";
  // retrying for a few seconds is the usual cure (unverified on macOS).
  const bootstrap = async (label: string) => {
    for (let i = 0; ; i++) {
      const r = await run('launchctl', ['bootstrap', domain, file(label)]);
      if (r.code === 0) return;
      if (r.code === 127) throw new ServiceManagerError('launchctl is not available: Hallway manages services with launchd on macOS');
      if (i >= 10) throw new ServiceManagerError(`launchctl bootstrap ${domain} ${file(label)} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
      await sleep(500);
    }
  };

  // exit 3 / 113: "No such process" / "Could not find service": it wasn't loaded, which is what we wanted
  const bootout = (label: string) => launchctl(['bootout', target(label)], [0, 3, 36, 113]);

  return {
    kind: 'launchd',
    file,
    render: renderPlist,
    readPath: plistPath,
    async write(spec) {
      return writeIfChanged(file(spec.label), renderPlist(spec));
    },
    async start(spec) {
      // a `stop` disabled it, so it wouldn't come back at login; undo that first or bootstrap refuses
      await launchctl(['enable', target(spec.label)]);
      const st = await status(spec.label);
      if (st.running) return;
      if (!st.loaded) {
        await bootstrap(spec.label);
        if (spec.runAtLoad) return; // bootstrap starts a RunAtLoad job
      }
      await launchctl(['kickstart', target(spec.label)]);
    },
    async stop(label) {
      // bootout unloads it, so KeepAlive can't resurrect it; disable keeps it from loading at the next login
      await bootout(label);
      await launchctl(['disable', target(label)]);
    },
    async restart(spec, { reload = false } = {}) {
      const st = await status(spec.label);
      if (!st.loaded) return this.start(spec);
      if (!reload) {
        await launchctl(['kickstart', '-k', target(spec.label)]);
        return;
      }
      // a changed plist is only read at bootstrap
      await bootout(spec.label);
      await launchctl(['enable', target(spec.label)]);
      await bootstrap(spec.label);
      if (!spec.runAtLoad) await launchctl(['kickstart', target(spec.label)]);
    },
    status,
    async remove(label) {
      await bootout(label);
      // clear the disabled override a `stop` may have left, so a later install of the same label just works
      await launchctl(['enable', target(label)]);
      removeFile(file(label));
    },
    list() {
      try {
        return fs
          .readdirSync(dir)
          .filter((f) => /^hallway\.[a-z0-9.-]+\.plist$/.test(f))
          .map((f) => f.slice(0, -'.plist'.length))
          .sort();
      } catch {
        return [];
      }
    },
  };
}
