// Linux: systemd user units (D26), the equivalent of the launchd LaunchAgents in launchd.ts. The mapping:
//   RunAtLoad          → `[Install] WantedBy=default.target`, and `systemctl --user enable`
//   KeepAlive          → `Restart=always` (a `systemctl stop` is never undone by it)
//   ThrottleInterval   → `RestartSec=10`
//   StandardOut/ErrorPath → `StandardOutput=append:<file>` / `StandardError=append:<file>`, in the data home's logs/
// Units are named `hallway-daemon.service` and `hallway-app-<slug>.service` (D40): the hyphenated prefix lets one
// drop-in directory, `hallway-.service.d/`, apply to all of them.
import fs from 'node:fs';
import path from 'node:path';
import { type Runner, type ServiceManager, ServiceManagerError, type ServiceSpec, type ServiceStatus, defaultRunner, removeFile, writeIfChanged } from './services.js';

/** `hallway.app.my-app` → `hallway-app-my-app.service`. Slugs have no dots, so this can't collide. */
export const unitName = (label: string) => `${label.replace(/\./g, '-')}.service`;
/** The other way: `hallway-app-my-app.service` → `hallway.app.my-app`. */
export function labelOf(unit: string): string | null {
  const m = /^hallway-(daemon|caddy|dnsmasq|app-([a-z0-9][a-z0-9-]*))\.service$/.exec(unit);
  if (!m) return null;
  return m[2] ? `hallway.app.${m[2]}` : `hallway.${m[1]}`;
}

/** `%` starts a specifier everywhere in a unit file; `$` an environment variable in ExecStart. */
const pct = (s: string) => s.replace(/%/g, '%%');
const cEscape = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t');

/** One ExecStart word: specifiers and variables escaped, quoted when it has to be. */
export function execWord(a: string): string {
  const s = pct(a).replace(/\$/g, '$$$$');
  return s === '' || /[\s"'\\;]/.test(s) ? `"${cEscape(s)}"` : s;
}

/** The unit for a job. Pure: the golden files in test/fixtures/services/ pin it. */
export function renderUnit(spec: ServiceSpec): string {
  const lines = [
    `# Generated by Hallway (${spec.label}). Don't edit it: \`hallway service regenerate\` rewrites it.`,
    ...(spec.node ? [`# Node ${spec.node.version}: ${spec.node.path}`] : []),
    '[Unit]',
    `Description=${pct(spec.description)}`,
    '',
    '[Service]',
    'Type=simple',
    `WorkingDirectory=${pct(spec.cwd)}`,
    `ExecStart=${spec.program.map(execWord).join(' ')}`,
    ...Object.entries(spec.env).map(([k, v]) => `Environment="${cEscape(pct(`${k}=${v}`))}"`),
    `StandardOutput=append:${pct(spec.stdout)}`,
    `StandardError=append:${pct(spec.stderr)}`,
    `Restart=${spec.keepAlive ? 'always' : 'no'}`,
    'RestartSec=10',
    ...(spec.runAtLoad ? ['', '[Install]', 'WantedBy=default.target'] : []),
    '',
  ];
  return lines.join('\n');
}

/** The PATH an existing unit sets (for doctor), or null. */
export function unitPath(text: string): string | null {
  const m = /^Environment="PATH=((?:[^"\\]|\\.)*)"$/m.exec(text);
  return m ? m[1].replace(/\\(.)/g, (_, c) => (c === 'n' ? '\n' : c === 't' ? '\t' : c)).replace(/%%/g, '%') : null;
}

/** `systemctl --user show -p …` output: KEY=VALUE lines. */
export function parseShow(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const i = line.indexOf('=');
    if (i > 0) out[line.slice(0, i)] = line.slice(i + 1).trim();
  }
  return out;
}

export interface SystemdOptions {
  /** ~/.config/systemd/user (or $XDG_CONFIG_HOME/systemd/user). */
  dir: string;
  run?: Runner;
}

const SHOW_PROPS = 'LoadState,ActiveState,SubState,MainPID,ExecMainStatus,ExecMainPID,UnitFileState';

export function systemdManager({ dir, run = defaultRunner }: SystemdOptions): ServiceManager {
  const file = (label: string) => path.join(dir, unitName(label));

  const systemctl = async (args: string[], okCodes: number[] = [0]) => {
    const r = await run('systemctl', ['--user', ...args]);
    if (r.code === 127) throw new ServiceManagerError("systemctl is not available: Hallway's services need systemd's per-user instance (`systemctl --user`)");
    if (/Failed to connect to (user scope )?bus|DBUS_SESSION_BUS_ADDRESS|XDG_RUNTIME_DIR/.test(r.stderr))
      throw new ServiceManagerError(
        `can't reach systemd's per-user instance (${r.stderr.trim()}). Run Hallway from a login session, or check that $XDG_RUNTIME_DIR is set (usually /run/user/$(id -u)).`,
      );
    if (!okCodes.includes(r.code)) throw new ServiceManagerError(`systemctl --user ${args.join(' ')} failed (exit ${r.code}): ${(r.stderr || r.stdout).trim()}`);
    return r;
  };

  const status = async (label: string): Promise<ServiceStatus> => {
    const installed = fs.existsSync(file(label));
    const r = await systemctl(['show', unitName(label), `--property=${SHOW_PROPS}`], [0, 1, 4]);
    const p = parseShow(r.stdout);
    const loaded = p.LoadState === 'loaded';
    const running = p.ActiveState === 'active' || p.ActiveState === 'reloading';
    const pid = Number(p.MainPID) || null;
    // ExecMainStatus is the exit status of the last run; meaningless while it's the one running now
    const exited = !running && Number(p.ExecMainPID) > 0;
    return {
      label,
      installed,
      loaded,
      running,
      pid: running ? pid : null,
      lastExitCode: exited && /^-?\d+$/.test(p.ExecMainStatus ?? '') ? Number(p.ExecMainStatus) : null,
      state: p.ActiveState ? `${p.ActiveState}${p.SubState ? ` (${p.SubState})` : ''}` : null,
      enabled: p.UnitFileState ? p.UnitFileState === 'enabled' || p.UnitFileState === 'enabled-runtime' : null,
    };
  };

  const enableAsAsked = (spec: ServiceSpec) => systemctl([spec.runAtLoad ? 'enable' : 'disable', '--quiet', unitName(spec.label)]);

  return {
    kind: 'systemd',
    file,
    render: renderUnit,
    readPath: unitPath,
    async write(spec) {
      const changed = writeIfChanged(file(spec.label), renderUnit(spec));
      if (changed) await systemctl(['daemon-reload']);
      return changed;
    },
    async start(spec) {
      await enableAsAsked(spec);
      await systemctl(['start', unitName(spec.label)]);
    },
    async stop(label) {
      await systemctl(['stop', unitName(label)], [0, 5]);
      // so it doesn't come back at the next login either (D41); 1: no such unit, which is fine here
      if (fs.existsSync(file(label))) await systemctl(['disable', '--quiet', unitName(label)], [0, 1]);
    },
    async restart(spec) {
      // `write` already ran daemon-reload for a changed unit, and restart starts an inactive one
      await enableAsAsked(spec);
      await systemctl(['restart', unitName(spec.label)]);
    },
    status,
    async remove(label) {
      await systemctl(['stop', unitName(label)], [0, 5]);
      if (fs.existsSync(file(label))) await systemctl(['disable', '--quiet', unitName(label)], [0, 1]);
      removeFile(file(label));
      await systemctl(['daemon-reload']);
      await systemctl(['reset-failed', unitName(label)], [0, 1, 5]);
    },
    list() {
      try {
        return fs
          .readdirSync(dir)
          .map(labelOf)
          .filter((l): l is string => l !== null)
          .sort();
      } catch {
        return [];
      }
    },
  };
}
